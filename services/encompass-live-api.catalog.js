/**
 * Development work by David Lane
 *
 * Allowlisted ICE Developer Connect operations for Enhanced Conditions.
 * Paths are templates only — invoke substitutes {params} and never accepts a free-form URL.
 */
function op(entry) {
  const method = String(entry.method || 'GET').toUpperCase();
  const pathParams = [...(entry.path.matchAll(/\{([^}]+)\}/g) || [])].map((m) => m[1]);
  return {
    destructive: method !== 'GET',
    pathParams,
    queryKeys: [],
    defaultQuery: {},
    sampleBody: null,
    notes: '',
    action: 'list',
    ...entry,
    method,
    pathParams: entry.pathParams || pathParams,
  };
}

