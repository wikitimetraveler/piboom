export const CATALOGS = {
  conditions: CONDITIONS_CATALOG,
};

export function getCatalog(domain) {
  return CATALOGS[domain] || null;
}

export function findOperation(domain, operationId) {
  const catalog = getCatalog(domain);
  if (!catalog) return null;
  return catalog.find((item) => item.id === operationId) || null;
}
